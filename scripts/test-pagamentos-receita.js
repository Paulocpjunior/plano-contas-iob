'use strict';
const assert = require('assert');
const { proporBaixa, componentes, centavos } = require('../pagamentos-receita');
const { acaoDaRota } = require('../permissoes-cci');
// Dados artificiais, contas sem relação com qualquer cliente.
const contas = ['banco','tributo','multa','juros'].map((descricao, i) => ({ codigo: '1.' + i, reduzido: String(i + 1), descricao, analitica: true }));
const documento = { numeroDocumento: '123', tipo: { sigla: 'DARF' }, receita: { codigo: '9999' },
  periodoApuracao: '2026-09-01', dataArrecadacao: '2026-10-12', valorPrincipal: 100, valorMulta: 2, valorJuros: 3, valorTotal: 105, desmembramentos: [] };
const base = { documento, fonte: 'serpro', contas, mapeamento: { banco: '1', receitas: { '9999': '2' }, multa: '3', juros: '4' }, entries: [], cnpj: '00000000000000', competencia: '2026-09' };
const run = (d = {}, extras = {}) => proporBaixa({ ...base, ...extras, documento: { ...documento, ...d } });
let p = run(); assert(p.ok, p.erros.join()); assert.equal(p.periodo, '2026-10');
assert.equal(p.lancamentos.reduce((s,l) => s + l.valor, 0), -105);
assert.deepEqual(p.partidas.map(x => x.contaDebito), ['2','3','4']);
assert(p.partidas.every(x => x.contaCredito === '1')); assert(p.lancamentos.every(l => l.data === '2026-10-12'));
assert(!run({}, { fonte: 'dry_run' }).ok);
p = run({ valorMulta: null, valorJuros: null, valorTotal: 100 }); assert(p.ok); assert.equal(p.partidas.length, 1); assert.equal(p.documento.valorMulta, null);
assert(!run({ valorMulta: null }).ok); assert(!run({ valorPrincipal: null }).ok);
assert(!run({ valorPrincipal: '100' }).ok); assert(!run({ valorPrincipal: -100 }).ok);
assert(!run({ valorTotal: null }).ok); assert(!run({ dataArrecadacao: '2026-02-30' }).ok);
assert(!run({}, { competencia: '2026-10' }).ok);
assert(!run({}, { mapeamento: { banco: '1' } }).ok);
assert(!run({}, { contas: contas.map(c => ({ ...c, analitica: false })) }).ok);
assert(!run({}, { contas: [...contas, { ...contas[0] }] }).ok);
assert(run({}, { contas: [...contas, { codigo: '1', analitica: false }] }).ok, 'reduzido analítico vence grupo sintético como no CCI');
assert(!run({ tipo: { sigla: 'DAS' } }).ok);
assert(!run({}, { entries: [{ id: 'x', documento: '123', data: '2026-10-11', valor: -104 }] }).ok);
p = run({}, { entries: [{ id: 'x', data: '12/10/2026', valor: -105, contaDebito: 'x', contaCredito: 'y' }] });
assert(!p.ok); assert.equal(p.existentes[0].diferencaValor, 0); assert.equal(p.existentes[0].contasPropostas, false);
assert(run({}, { entries: [{ id: 'x', data: '13/10/2026', valor: -105 }] }).ok);
const parcelas = [ { ...documento, valorTotal: 52, valorPrincipal: 50, valorMulta: 1, valorJuros: 1 }, { ...documento, valorTotal: 53, valorPrincipal: 50, valorMulta: 1, valorJuros: 2 } ];
p = run({ desmembramentos: parcelas }); assert(p.ok); assert.equal(p.lancamentos.length, 6); assert.equal(p.lancamentos.reduce((s,l) => s+l.valor,0), -105);
assert(!run({ desmembramentos: parcelas, valorPrincipal: 99, valorMulta: 3 }).ok);
assert(!run({ desmembramentos: parcelas.map(d => ({ ...d, valorPrincipal: null })) }).ok);
assert.equal(componentes({ ...documento, desmembramentos: [{ receita: documento.receita, valorPrincipal: null, valorMulta: null, valorJuros: null }] })[0].valorPrincipal, 100);
assert(!run({ desmembramentos: [{ receita: { codigo: '8888' } }] }).ok);
assert.equal(centavos(null), null); assert.throws(() => centavos(0.001));
assert.equal(acaoDaRota('POST','/api/empresas/x/pagamentos-receita/consultar'), null);
assert.equal(acaoDaRota('POST','/api/empresas/x/pagamentos-receita/previa'), null);
assert.equal(acaoDaRota('POST','/api/empresas/x/pagamentos-receita/confirmar'), 'importar');
console.log('DARF: composição, ausências, desmembramentos, contas, competência, duplicidade e permissões OK');
