const assert = require('assert');
const { __test__: { parsearPaginasCaixaModerno: parse } } = require('../parser-caixa-extrato');
const pages = require('./fixtures/caixa-sbe-items.json');
const r = parse(pages);
assert.equal(r.lancamentos.length,32);
assert.equal(r.total_credito,1884822.07);
assert.equal(r.total_debito,1902891.50);
assert.equal(r.saldo_inicial,0);
assert.equal(r.saldo_final,-18069.43);
assert.equal(r.cnpj_detectado,'04.496.421/0001-06');
assert.equal(r.conta_detectada,'AG-01041/CC-000577563629-1');
assert.equal(r.periodo_solicitado_fim,'2026-01-31');
assert.equal(r.periodo_fim,'2026-02-02');
assert.equal(r.lancamentos.filter(l=>l.data==='2026-02-02').length,2);
assert(r.lancamentos.some(l=>l.valor===-508000 && /TORRE FORTE/.test(l.descricao)));
assert(r.lancamentos.some(l=>l.valor===28000 && l.saldo<0));
assert(!r.lancamentos.some(l=>/SALDO DIA/.test(l.descricao)));
const corrupt = structuredClone(pages);
corrupt[0].find(i=>i.str==='- R$ 54,19').str='R$ 54,19';
assert.throws(()=>parse(corrupt),/diverge do saldo/);
const missing = structuredClone(pages);
missing[0] = missing[0].filter(i=>!(i.str==='000000' && Math.abs(i.transform[5]-587.67)<1));
assert.throws(()=>parse(missing),/quantidade/);
assert.equal(parse([[{str:'Outro banco',transform:[1,0,0,1,0,0]}]]).detectado,false);
