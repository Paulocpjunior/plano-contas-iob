'use strict';
const assert=require('assert');
const {catalogo,configurar,preparar}=require('../crm-automacoes');
assert.equal(catalogo.length,8);
const b={revisao:0,modelo:'Olá {{empresa}}',destino:'admin@example.com',motivo:'Configuração'};
assert.equal(configurar('A01',{},b,'admin','agora').ativa,false);
assert.throws(()=>configurar('A01',{}, {...b,ativa:true},'u','t'),/não estão habilitados/);
assert.throws(()=>configurar('A01',{}, {...b,revisao:1},'u','t'),/mudou/);
assert.throws(()=>configurar('A01',{}, {...b,modelo:'{{segredo}}'},'u','t'),/desconhecida/);
assert.throws(()=>configurar('A01',{}, {...b,modelo:'{{empresa}'},'u','t'),/formato/);
assert.throws(()=>configurar('A01',{}, {...b,destino:'a@example.com;b@example.com'},'u','t'),/único/);
assert.throws(()=>configurar('A04',{}, {...b,destino:'https://evil.test'},'u','t'),/Teams/);
assert.throws(()=>configurar('A05',{}, b,'u','t'),/destinatário/);
const empresa={razao_social:'Empresa',cnpj:'12345678901234'};
assert.throws(()=>preparar('A02',{}, {evento:'cadastro_editado'},empresa),/Gatilho/);
assert.throws(()=>preparar('A03',{}, {evento:'cadastro_criado'},empresa),/Gatilho/);
const evento={evento:'manual',categoria:'DITR',exercicio:'2026',link:'https://example.com/ditr.pdf'};
const p=preparar('A06',{},evento,empresa);assert(p.mensagem.includes('DITR'));assert(!p.mensagem.includes('DEFIS'));assert.equal(p.envio_realizado,false);
assert.throws(()=>preparar('A06',{}, {...evento,categoria:'DEFIS'},empresa),/próprio/);
assert.throws(()=>preparar('A06',{}, {...evento,link:'https://user:pass@example.com'},empresa),/credenciais/);
assert.throws(()=>preparar('A06',{}, {...evento,link:'javascript:alert(1)'},empresa),/HTTPS/);
assert.throws(()=>preparar('A08',{}, {},empresa),/Conferir Checklist/);
assert.throws(()=>preparar('A01',{}, {evento:'cadastro_criado'},{cnpj:empresa.cnpj}),/razão social/);
console.log('CRM automações: modelos, revisão, gatilhos e bloqueio de envio conferidos.');
const varios=configurar('A01',{}, {...b,destino:undefined,canal:'email',destinatarios:['um@example.com','dois@example.com','um@example.com']},'admin','t');
assert.deepEqual(varios.destinatarios,['um@example.com','dois@example.com']);
assert.equal(varios.canal,'email');
assert.equal(configurar('A01',{}, {...b,canal:'teams',destinatarios:['https://teams.microsoft.com/l/chat/fixture']},'u','t').canal,'teams');
assert.throws(()=>configurar('A01',{}, {...b,canal:'sms'},'u','t'),/Escolha/);
assert.throws(()=>configurar('A01',{}, {...b,destinatarios:Array(21).fill('a@example.com')},'u','t'),/vinte/);
assert.throws(()=>configurar('A01',{}, {...b,destinatarios:['']},'u','t'),/destinatário/);
