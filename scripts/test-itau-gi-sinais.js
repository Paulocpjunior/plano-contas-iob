const assert=require('assert');
const h=require('../parser-itau-extrato-mensal').__test__;
const fixture=require('./fixtures/itau-gi-fevereiro-ocr.json');
for(const f of require('./fixtures/itau-gi-sinais-pixels.json')) assert.equal(h.possuiMenosImpresso(f.pixels,f.width,f.height,f.alturaFonte),f.negative,f.text);
const r=h.parseItauLancamentosPeriodo(fixture.lines,fixture.textoCompleto);
assert.equal(r.lancamentos.length,25);
assert.equal(Math.round(r.total_credito*100),1256856);
assert.equal(Math.round(r.total_debito*100),1057060);
assert.equal(r.saldo_anterior,2723.87);
assert.equal(r.saldo_final,4721.83);
assert.equal(r.saldos_conciliados,true);
assert.equal(r.totais_calculados,true);
assert.equal(r.lancamentos.find(l=>/CEF MATRIZ/.test(l.descricao)).valor,-319.79);
assert.equal(r.lancamentos.find(l=>/DEBITO SEGURO/.test(l.descricao)).valor,-18.07);
const asc=[...fixture.lines].reverse();
assert.equal(h.parseItauLancamentosPeriodo(asc,fixture.textoCompleto).saldo_final,4721.83);
const corrupt=JSON.parse(JSON.stringify(fixture).replaceAll('-319,79','319,79'));
assert.throws(()=>h.parseItauLancamentosPeriodo(corrupt.lines,corrupt.textoCompleto),/nao conciliou/);
const missing=fixture.lines.filter(l=>!/SALDO TOTAL DISPON/.test(l.text));
assert.throws(()=>h.parseItauLancamentosPeriodo(missing,missing.map(l=>l.text).join('\n')),/saldos de abertura e fechamento/);
console.log('OK Itau Gi: sinais impressos, ordem inversa, fechamento no ultimo dia com movimento e bloqueio de inversao.');
