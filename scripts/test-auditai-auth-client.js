'use strict';
const assert = require('assert/strict');
const fs = require('fs');
const { createClient, authFromCci } = require('../auditai/auth-client');
const origin = 'https://cci.example';
const url = origin + '/api/auditai/extrair-pdf-contabil';
const body = JSON.stringify({ data: 'PDF_BASE64_TESTE' });
function setup(statuses = [200]) {
  const tokens = [], requests = [];
  const user = { getIdToken: async force => { tokens.push(force); return force ? 'renewed' : 'cached'; } };
  const auth = { currentUser: user, authStateReady: async () => {} };
  const client = createClient(auth, async input => { requests.push(input); return new Response('{}', { status: statuses.shift() || 200 }); }, origin);
  return { auth, user, client, tokens, requests };
}
(async () => {
  let s = setup([401, 200]);
  const response = await s.client.request(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body });
  assert.equal(response.status, 200);
  assert.deepEqual(s.tokens, [false, true]);
  assert.equal(s.requests.length, 2);
  assert.equal(await s.requests[0].text(), body);
  assert.equal(await s.requests[1].text(), body);
  assert.equal(s.requests[1].headers.get('Authorization'), 'Bearer renewed');
  s = setup([401, 401]);
  await assert.rejects(s.client.request(url, { method: 'POST', body }), e => e.status === 401 && e.message.includes('arquivo selecionado foi preservado'));
  assert.equal(s.requests.length, 2, 'renovação limitada a uma repetição');
  s = setup([403]);
  assert.equal((await s.client.request(url)).status, 403);
  assert.deepEqual(s.tokens, [false], 'permissão negada não força renovação');
  s = setup();
  s.auth.currentUser = null;
  let ready;
  s.auth.authStateReady = () => new Promise(resolve => { ready = () => { s.auth.currentUser = s.user; resolve(); }; });
  const pending = s.client.request(url);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(s.requests.length, 0, 'espera restauração antes de enviar o arquivo');
  ready(); await pending;
  assert.equal(s.requests.length, 1);
  s = setup(); s.auth.currentUser = null;
  await assert.rejects(s.client.request(url), e => e.status === 401);
  assert.equal(s.requests.length, 0, 'sessão ausente não usa token antigo nem envia o documento');
  s = setup();
  await s.client.request('https://other.example/api/gemini/generate');
  assert.equal(s.tokens.length, 0, 'token nunca segue para outro domínio');
  await s.client.request(origin + '/api/health');
  assert.equal(s.tokens.length, 0, 'requisição fora do AuditAI permanece intacta');
  s = setup();
  s.user.getIdToken = async () => { s.auth.currentUser = { uid: 'outro' }; return 'old'; };
  await assert.rejects(s.client.request(url), e => e.status === 401);
  assert.equal(s.requests.length, 0, 'troca de conta interrompe envio');
  s = setup(); s.user.getIdToken = async () => { throw new Error('auth/user-token-expired'); };
  await assert.rejects(s.client.getToken(), e => e.status === 401 && !e.message.includes('auth/user-token-expired'));
  s = setup();
  const host = { location: { origin }, opener: { location: { origin }, firebase: { auth: () => s.auth } } };
  assert.equal(authFromCci(host).currentUser, s.user, 'usa sessão real da aba CCI');
  host.opener.location.origin = 'https://other.example';
  assert.equal(authFromCci(host).currentUser, null, 'não usa sessão de outra origem');
  await assert.rejects(authFromCci(host).authStateReady(), e => e.status === 401);
  const html = fs.readFileSync(require.resolve('../auditai/index.html'), 'utf8');
  const bundle = fs.readFileSync(require.resolve('../auditai/assets/index-DREfix3266.js'), 'utf8');
  assert.ok(html.indexOf('auth-client.js') < html.indexOf('index-DREfix3266.js'));
  assert.ok(bundle.includes('window.AuditAiAuth.install()'));
  assert.ok(!bundle.includes('sessionStorage.getItem("sp_firebase_token")'));
  assert.ok(bundle.includes('if(i===401||i===403||'), 'retry de IA não repete sessão inválida');
  assert.ok(bundle.includes('PDF_SEM_TEXTO_ESTRUTURADO'), 'OCR permanece disponível para PDFs digitalizados');
  console.log('OK: sessão restaurada, renovação única, corpo preservado, conta e domínio protegidos, OCR mantido.');
})().catch(e => { console.error(e); process.exitCode = 1; });
