const assert=require('assert');
const U=require('../reinf/reinf-alugueis-planilha');
const fixture=require('./fixtures/reinf-igrejas-agosto-anonimizado.json');
const a=U.analisar(fixture.abas);
assert.equal(a.modelo,'igrejas');assert.equal(a.competencia,'2026-08');
assert.equal(a.registros.length,88);assert.equal(a.registros.filter(r=>r.tipo==='reinf').length,70);
assert.equal(a.registros.filter(r=>r.tipo==='locador_pj').length,18);
assert.equal(new Set(a.registros.map(r=>r.documento)).size,5);
assert.equal(a.registros.reduce((s,r)=>s+r.aluguel,0),54513077);
assert.equal(a.registros.reduce((s,r)=>s+(r.irrf||0),0),2475741);
assert(a.registros.every(r=>r.data===''),'Apuração não pode virar data de pagamento');
assert.equal(a.registros.filter(r=>r.pendencias.some(p=>p.includes('difere'))).length,10);
assert(a.registros.some(r=>r.irrf===null),'retenção ausente não vira zero');
const source=a.registros.find(r=>r.aba==='Igreja 2').documento;
const rs=a.registros.filter(r=>r.tipo==='reinf'&&r.documento===source);
const rev=Object.fromEntries(rs.map(r=>[r.id,{conferido:true,data:'2026-08-08',base:r.aluguel}]));
const dados=U.preparar(a,[],rev,source,a.competencia);
assert.equal(dados.length,3);assert(dados.every(b=>b.cnpjFonte===source&&b.dtPagamento==='2026-08-08'&&b.valorIrrf===0));
rev[rs[0].id].data='';assert.throws(()=>U.preparar(a,[],rev,source,a.competencia),/data real/);
rev[rs[0].id].data='2026-09-08';assert.throws(()=>U.preparar(a,[],rev,source,a.competencia),/data real/);
rev[rs[0].id].data='2026-08-08';rev[rs[0].id].base=null;assert.throws(()=>U.preparar(a,[],rev,source,a.competencia),/base/);
assert.throws(()=>U.preparar(a,[],rev,'11135442000161',a.competencia),/Nenhum/);
const proximo=structuredClone(fixture);proximo.abas.forEach(s=>s.rows.forEach(r=>r.forEach((v,i)=>{if(v==='2026-08-01')r[i]='2026-09-01';})));
assert.equal(U.analisar(proximo.abas).competencia,'2026-09');
assert.throws(()=>U.analisar([...fixture.abas,{nome:'IR PF x PJ',rows:[]}]),/Separe/);
console.log('OK: igrejas 88 linhas, 5 fontes, 70 PF e 18 PJ; totais, retenção preservada, datas e base obrigatórias, mês variável e modelo misto bloqueado.');
