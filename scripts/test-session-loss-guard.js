'use strict';
const assert=require('assert'),fs=require('fs');
const {validarPerdaLancamentos:check}=require('../session-loss-guard');
const a={id:'a',valor:10},b={id:'b',valor:20},old={entries:[a,b]};
assert(check(old,{entries:[a,b,{id:'c'}]}).ok);
assert(check(old,{entries:[{...a,valor:11},b]}).ok);
assert(!check(old,{entries:[a]}).ok);
assert(!check(old,{entries:[a,{id:'c'}]}).ok,'mesma quantidade também pode perder ID');
assert(!check(old,{entries:[]},{zerada:true},{is_admin:false}).ok);
assert(check(old,{entries:[]},{zerada:true},{is_admin:true}).ok);
const event={tipo:'exclusao_lancamento',em:'agora',lancamento:b};
assert(check(old,{entries:[a],auditoriaLancamentos:[event]}).ok);
assert(!check({...old,auditoriaLancamentos:[event]},{entries:[a],auditoriaLancamentos:[event]}).ok,'evento antigo não autoriza nova perda');
assert(!check(old,{entries:[a],auditoriaLancamentos:[{...event,lancamento:{...b,valor:21}}]}).ok);
assert(!check({entries:[{valor:1},{valor:1}]},{entries:[{valor:1}]}).ok);
// Substituição de movimento do CFI (31/10): um evento lista as linhas que saem, pelo id.
const sub={tipo:'substituicao_movimento_cfi',em:'agora',lancamentos:[{id:'b',cfop:'1101'}]};
assert(check(old,{entries:[a,{id:'c'}],auditoriaLancamentos:[sub]}).ok,'substituição registrada autoriza a saída da linha antiga');
assert(!check({...old,auditoriaLancamentos:[sub]},{entries:[a],auditoriaLancamentos:[sub]}).ok,'substituição antiga não autoriza nova perda');
assert(!check(old,{entries:[{id:'c'}],auditoriaLancamentos:[sub]}).ok,'só sai o que o evento lista');
const semId={valor:7,descricao:'antiga'};
assert(check({entries:[a,semId]},{entries:[a],auditoriaLancamentos:[{...sub,lancamentos:[{completo:semId}]}]}).ok,'linha sem id: a cópia inteira autoriza');
assert(!check({entries:[a,semId]},{entries:[a],auditoriaLancamentos:[{...sub,lancamentos:[{valor:7}]}]}).ok,'linha sem id: resumo não basta');
const lote=require('../lancamentos-edicao-lote');
const estadoAntes={entries:[a,b,semId]};
const estadoDepois=JSON.parse(JSON.stringify(estadoAntes));
lote.registrarSubstituicao(estadoDepois,[b,semId],{periodos:[]});
estadoDepois.entries=[a,{id:'c'}];
assert(check(estadoAntes,estadoDepois).ok,'o evento que a tela grava é o que o servidor aceita');
const server=fs.readFileSync(require('path').join(__dirname,'../server.js'),'utf8');
assert(server.includes('const perda = validarPerdaLancamentos('));
console.log('OK: perda parcial, total, mesma contagem e repetição de exclusão bloqueadas; edição e exclusão auditada preservadas.');
