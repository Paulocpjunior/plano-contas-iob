const assert=require('assert');
const parse=require('../parser-caixa-extrato').__test__.parsearPaginasCaixaDuasDatas;
const pages=require('./fixtures/caixa-sbe-fevereiro-items.json');
const r=parse(pages);
assert.equal(r.lancamentos.length,16);
assert.equal(r.total_credito,100182.64);
assert.equal(r.total_debito,85850.12);
assert.equal(r.cnpj_detectado,'04.496.421/0001-06');
assert.equal(r.conta_detectada,'AG-01041/CC-000577563629-1');
assert.equal(r.periodo_solicitado_fim,'2026-02-28');
assert.equal(r.periodo_fim,'2026-03-02');
assert.equal(r.lancamentos.filter(l=>l.data==='2026-03-02').length,2);
assert.equal(r.lancamentos.find(l=>l.documento==='41712').valor,-10171.8);
assert.equal(r.lancamentos[0].descricao,'TARIFA RENOVACAO CADASTRO');
assert(!r.lancamentos.some(l=>/SALDO DIA/.test(l.descricao)));
assert.equal(r.saldo_inicial,undefined);
const corrupt=structuredClone(pages);
corrupt[0].find(i=>i.str==='- 74,78').str='74,78';
assert.throws(()=>parse(corrupt),/diverge do saldo/);
const missing=structuredClone(pages);
missing[0]=missing[0].filter(i=>i.str!=='41712');
assert.throws(()=>parse(missing),/quantidade/);
console.log('OK Caixa duas datas: movimentos, sinal separado, saldos e periodo real.');
