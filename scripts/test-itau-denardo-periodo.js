const assert = require('assert');
const h = require('../parser-itau-extrato-mensal').__test__;
const fixture = require('./fixtures/itau-denardo-fevereiro-ocr.json');
const { leitura } = fixture;
const parse = o => h.parseItauLancamentosPeriodo(o.lines, o.textoCompleto);
const r = parse(leitura);
assert.equal(fixture.paginas, 6);
assert.equal(r.conta_detectada, 'AG-8105/CC-0010497-3');
assert.equal(r.periodo_inicio, '2026-02-01');
assert.equal(r.periodo_fim, '2026-02-28');
assert.equal(r.lancamentos.length, 185);
assert.equal(r.dias_conciliados, 18);
assert.equal(r.saldos_conciliados, true);
assert.equal(r.saldo_anterior, 116275);
assert.equal(r.saldo_final, 68740.33);
assert.equal(r.total_credito, 353800.69);
assert.equal(r.total_debito, 353800.69);
const economicos = r.lancamentos.filter(l => !l.movimentoAplicacaoAutomatica);
const automaticos = r.lancamentos.filter(l => l.movimentoAplicacaoAutomatica);
assert.equal(economicos.length, 167);
assert.equal(automaticos.length, 18);
assert.equal(economicos.reduce((n,l) => n + Math.max(0,Math.round(l.valor*100)),0), 21481931);
assert.equal(economicos.reduce((n,l) => n - Math.min(0,Math.round(l.valor*100)),0), 26235398);
assert(r.lancamentos.some(l => l.data === '2026-02-10' && l.valor === -1013.11));
assert(r.lancamentos.some(l => l.data === '2026-02-11' && l.valor === -1725.30));
assert(r.lancamentos.some(l => l.data === '2026-02-11' && l.valor === -1488.66));
assert(r.lancamentos.some(l => l.data === '2026-02-11' && l.valor === -3402.04));
assert(automaticos.some(l => l.data === '2026-02-27' && l.valor === -3217.11));
assert(!r.lancamentos.some(l => /^SALDO|^SDO/i.test(l.descricao)));
assert(r.lancamentos.every(l => l.data >= r.periodo_inicio && l.data <= r.periodo_fim));
const remover = predicado => {
  const o = structuredClone(leitura);
  o.lines = o.lines.filter(l => !predicado(l));
  o.textoCompleto = o.lines.map(l => l.text).join('\n');
  return o;
};
assert.throws(() => parse(remover(l => /^27\/02\/2026 APL APLIC/.test(l.text))), /nao conciliou/,
  'Saldo consolidado fecha sem transferência interna, mas saldo da conta deve bloquear');
assert.throws(() => parse(remover(l => l.page === 3)), /nao conciliou/);
assert.throws(() => parse(remover(l => /^10\/02\/2026 SALDO TOTAL/.test(l.text))), /nao conciliou/);
// Exerce diretamente a conferência com fluxos opostos, sem alterar o fechamento.
const fluxos = structuredClone(r.lancamentos);
fluxos.find(l => l.data === '2026-02-02' && !l.movimentoAplicacaoAutomatica).valor += 1;
fluxos.find(l => l.data === '2026-02-03' && !l.movimentoAplicacaoAutomatica).valor -= 1;
assert.equal(h.conferirSaldosDiariosItau(leitura.lines,fluxos,r.saldo_anterior).valido,false);
assert.equal(h.normalizarTokenMonetarioPosicionalOCR('-3.21711',480,'D'),'-3.217,11');
assert.equal(h.normalizarTokenMonetarioPosicionalOCR('2937',465,''),'2937');
assert.equal(h.normalizarTokenMonetarioPosicionalOCR('3.21711',300,'D'),'3.21711');
console.log('OK Itaú Denardo: OCR real, 185 movimentos, 18 dias, transferências, sinais e bloqueios por divergência.');
